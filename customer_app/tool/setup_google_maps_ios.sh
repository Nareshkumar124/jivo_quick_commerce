#!/usr/bin/env bash
# Places the Google Maps SDK for iOS key for the customer app (DL-80).
#
# The key is never committed. It is written to the gitignored
# ios/Flutter/MapsKey.xcconfig as the build setting MAPS_API_KEY_IOS, which
# ios/Flutter/Debug.xcconfig and Release.xcconfig (also used by Profile)
# include optionally (#include?). Info.plist exposes it as GMSApiKey and
# AppDelegate.swift hands it to GMSServices.provideAPIKey. Without the file
# the app still builds and shows the no-map fallback.
#
# Key source, first match wins:
#   1. env MAPS_API_KEY_IOS
#   2. ~/.config/jivo-quick-commerce/google-maps/ios-api-key.txt (one line),
#      or $GOOGLE_MAPS_CONFIG_DIR/ios-api-key.txt
#
# Usage (from anywhere, on the Mac that builds iOS):
#   customer_app/tool/setup_google_maps_ios.sh --write
#   customer_app/tool/setup_google_maps_ios.sh --remove   # back to "no maps"
#
# The script never prints the key.
set -euo pipefail

mode=""
while [[ $# -gt 0 ]]; do
  case "$1" in
    --write) mode="write" ;;
    --remove) mode="remove" ;;
    -h|--help) sed -n '2,21p' "$0"; exit 0 ;;
    *) echo "Unknown option: $1 (use --write, --remove or --help)" >&2; exit 2 ;;
  esac
  shift
done
if [[ -z "$mode" ]]; then
  echo "Say what to do: --write or --remove (see --help)." >&2
  exit 2
fi

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
app_dir="$(cd "$script_dir/.." && pwd)"
rel="ios/Flutter/MapsKey.xcconfig"
dest="$app_dir/$rel"

if [[ "$mode" == "remove" ]]; then
  if [[ -e "$dest" ]]; then
    rm -f -- "$dest"
    echo "Removed $rel"
  else
    echo "Nothing to remove ($rel does not exist)"
  fi
  echo "Done. Rebuild the app: it builds without maps (manual address fallback)."
  exit 0
fi

config_dir="${GOOGLE_MAPS_CONFIG_DIR:-$HOME/.config/jivo-quick-commerce/google-maps}"
key_file="$config_dir/ios-api-key.txt"
if [[ -n "${MAPS_API_KEY_IOS:-}" ]]; then
  key="$MAPS_API_KEY_IOS"
  source_name="env MAPS_API_KEY_IOS"
elif [[ -f "$key_file" ]]; then
  key="$(head -n 1 "$key_file")"
  source_name="$key_file"
else
  echo "No iOS Maps key: set MAPS_API_KEY_IOS or create $key_file" >&2
  echo "(one line: a Maps SDK for iOS key restricted to the app's bundle ids)." >&2
  exit 1
fi
# Strip whitespace and a Windows CR.
key="$(printf '%s' "$key" | tr -d '[:space:]')"

# Google API keys are letters, digits, '-' and '_'. Anything else would be
# a wrong file or could break the xcconfig syntax, so refuse it.
if [[ -z "$key" || ! "$key" =~ ^[A-Za-z0-9_-]+$ ]]; then
  echo "The key from $source_name is empty or has unexpected characters; refusing." >&2
  exit 1
fi
if [[ "$key" != AIza* ]]; then
  echo "Warning: the key from $source_name does not start with 'AIza'; check it is a Google API key." >&2
fi

# Refuse to place the file where git would pick it up.
if git -C "$app_dir" rev-parse --is-inside-work-tree > /dev/null 2>&1; then
  if ! git -C "$app_dir" check-ignore -q "$rel"; then
    echo "$rel is not gitignored; refusing to continue." >&2
    exit 1
  fi
fi

umask 077
tmp="$(mktemp "$dest.XXXXXX")"
trap 'rm -f -- "$tmp"' EXIT
{
  echo "// Generated by tool/setup_google_maps_ios.sh. Gitignored: never commit."
  echo "MAPS_API_KEY_IOS = $key"
} > "$tmp"
chmod 600 "$tmp"
mv -f -- "$tmp" "$dest"
echo "Wrote $rel from $source_name"
echo "Done. Rebuild the app (Debug, Release and Profile all pick it up)."
