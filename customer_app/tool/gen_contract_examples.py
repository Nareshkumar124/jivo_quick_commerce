#!/usr/bin/env python3
"""Writes customer_app/test/fixtures/contract_examples.dart from the response
examples in backend/openapi/schema.yaml (the cart_*, orders_* and
payments_razorpay_verify operations), so the API repository tests decode the
contract's own examples. Run from anywhere after a schema change:

    python3 customer_app/tool/gen_contract_examples.py
"""
import json
import pathlib

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[2]
SCHEMA = ROOT / 'backend/openapi/schema.yaml'
OUT = ROOT / 'customer_app/test/fixtures/contract_examples.dart'
PREFIXES = (
    'cart_', 'orders_', 'payments_razorpay_verify',
    # P7 support and CMS (T-713).
    'support_tickets_', 'pages_retrieve', 'faqs_list',
)
# Generic guards (401/426/503) are covered elsewhere; orders_create keeps
# them for its gateway-unavailable 503.
SKIP_CODES = {'401', '426', '503'}


def main() -> None:
    schema = yaml.safe_load(SCHEMA.read_text())
    examples = {}
    for item in schema['paths'].values():
        for op in item.values():
            if not isinstance(op, dict):
                continue
            oid = op.get('operationId', '')
            if not oid.startswith(PREFIXES):
                continue
            for code, response in op.get('responses', {}).items():
                if code in SKIP_CODES and oid != 'orders_create':
                    continue
                for content in (response.get('content') or {}).values():
                    for name, example in (content.get('examples') or {}).items():
                        examples[f'{oid}/{code}/{name}'] = example.get('value')
    lines = [
        '// GENERATED by customer_app/tool/gen_contract_examples.py from',
        '// backend/openapi/schema.yaml. Do not edit: regenerate after a schema change.',
        '// The response examples of the cart, order, verify, support and CMS operations,',
        '// verbatim,'
        '// keyed "<operationId>/<status>/<example name>".',
        '// ignore_for_file: lines_longer_than_80_chars',
        '',
        "import 'dart:convert';",
        '',
        '/// The decoded example body for [key].',
        'Object? contractExample(String key) {',
        '  final raw = _examples[key];',
        "  if (raw == null) throw ArgumentError.value(key, 'key', 'no such example');",
        '  return jsonDecode(raw);',
        '}',
        '',
        'const _examples = <String, String>{',
    ]
    for key, value in examples.items():
        body = json.dumps(value, ensure_ascii=False)
        assert "'''" not in body
        lines.append(f"  {json.dumps(key)}: r'''{body}''',")
    lines.append('};')
    OUT.write_text('\n'.join(lines) + '\n')
    print(f'{len(examples)} examples -> {OUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
