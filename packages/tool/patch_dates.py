#!/usr/bin/env python3
"""Makes the generated dart-dio client send OpenAPI `format: date` values as
`YYYY-MM-DD` (api-request #38).

Used by generate_api.sh after generation, before build_runner. dart-dio maps
`format: date` to `DateTime` and json_serializable writes it with
`toIso8601String()` (`1998-04-02T00:00:00.000`), which DRF's DateField
rejects; date query parameters go out as `DateTime.toString()`
(`1998-04-02 00:00:00.000`). The Dart types stay `DateTime` (no app code
changes), responses still parse with `DateTime.parse`, and only the
outgoing encoding changes:

- every model property with `format: date` gets
  `@JsonKey(toJson: jivoDateToJson)` (or `jivoNullableDateToJson`);
- every query parameter with `format: date` is passed through
  `jivoDateToQuery`;
- `lib/src/date_only.dart` holds those functions.

The script fails if a date field it expects is not found in the generated
code, so a generator upgrade can't silently undo the fix.

Usage: patch_dates.py NORMALIZED_SPEC.json GENERATED_LIB_DIR
(standard library only)
"""

from __future__ import annotations

import json
import pathlib
import re
import sys
from typing import Any

IMPORT = "import 'package:jivo_api/src/date_only.dart';"

HELPER = """// GENERATED by packages/tool/patch_dates.py. Do not edit by hand.
//
// OpenAPI `format: date` values travel as `YYYY-MM-DD` (a calendar date, no
// time or zone). The Dart side keeps `DateTime`: the date is read from its
// own year/month/day fields, never converted to UTC first, so
// `DateTime(1998, 4, 2)` is sent as `1998-04-02` in any time zone.

String _two(int n) => n.toString().padLeft(2, '0');

/// `YYYY-MM-DD` for a `format: date` field.
String jivoDateToJson(DateTime date) {
  final year = date.year.toString().padLeft(4, '0');
  return '$year-${_two(date.month)}-${_two(date.day)}';
}

/// [jivoDateToJson] for an optional field.
String? jivoNullableDateToJson(DateTime? date) =>
    date == null ? null : jivoDateToJson(date);

/// A `format: date` query parameter.
String jivoDateToQuery(DateTime date) => jivoDateToJson(date);
"""


def is_date(schema: Any) -> bool:
    return isinstance(schema, dict) and schema.get("format") == "date"


def camel(name: str) -> str:
    parts = re.split(r"[_\-\s]+", name)
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def date_properties(spec: dict[str, Any]) -> dict[str, list[str]]:
    """Schema name -> its `format: date` property names."""
    found: dict[str, list[str]] = {}
    for name, schema in spec.get("components", {}).get("schemas", {}).items():
        for prop, prop_schema in (schema.get("properties") or {}).items():
            if is_date(prop_schema):
                found.setdefault(name, []).append(prop)
    return found


def date_query_params(spec: dict[str, Any]) -> dict[str, list[str]]:
    """Generated method name -> its `format: date` query parameter names."""
    found: dict[str, list[str]] = {}
    for item in spec.get("paths", {}).values():
        shared = item.get("parameters", [])
        for method in ("get", "put", "post", "patch", "delete", "head", "options"):
            op = item.get(method)
            if not op:
                continue
            for param in [*shared, *op.get("parameters", [])]:
                if param.get("in") == "query" and is_date(param.get("schema")):
                    found.setdefault(camel(op["operationId"]), []).append(
                        param["name"]
                    )
    return found


def add_import(source: str) -> str:
    if IMPORT in source:
        return source
    match = re.search(r"^import .*;$", source, flags=re.M)
    if match is None:
        return IMPORT + "\n" + source
    return source[: match.start()] + IMPORT + "\n" + source[match.start() :]


def patch_models(lib: pathlib.Path, props: dict[str, list[str]]) -> int:
    files = {}
    for path in (lib / "src" / "model").glob("*.dart"):
        if path.name.endswith(".g.dart"):
            continue
        for cls in re.findall(r"^class (\w+)\b", path.read_text(encoding="utf-8"), re.M):
            files[cls] = path
    patched = 0
    for schema, names in sorted(props.items()):
        path = files.get(schema)
        if path is None:
            sys.exit(f"patch_dates: no generated class {schema}")
        source = path.read_text(encoding="utf-8")
        for name in names:
            # The JsonKey of the property, then its field declaration.
            pattern = re.compile(
                r"(@JsonKey\(\s*name: r'" + re.escape(name) + r"',)"
                r"([^)]*\)\s*final (DateTime\??) \w+;)"
            )
            match = pattern.search(source)
            if match is None:
                sys.exit(f"patch_dates: {schema}.{name} is not a DateTime field")
            if "toJson:" in match.group(2):
                continue
            converter = (
                "jivoNullableDateToJson"
                if match.group(3).endswith("?")
                else "jivoDateToJson"
            )
            source = (
                source[: match.end(1)]
                + f" toJson: {converter},"
                + source[match.end(1) :]
            )
            patched += 1
        path.write_text(add_import(source), encoding="utf-8", newline="\n")
    return patched


def patch_queries(lib: pathlib.Path, params: dict[str, list[str]]) -> int:
    patched = 0
    remaining = {(m, p) for m, names in params.items() for p in names}
    for path in sorted((lib / "src" / "api").glob("*.dart")):
        source = path.read_text(encoding="utf-8")
        changed = False
        for method, names in params.items():
            head = re.search(r"\bFuture<Response<[^\n]*>> " + method + r"\(", source)
            if head is None:
                continue
            following = re.search(r"\bFuture<Response<", source[head.end() :])
            end = head.end() + following.start() if following else len(source)
            body = source[head.end() : end]
            for name in names:
                if f"r'{name}': jivoDateToQuery(" in body:
                    remaining.discard((method, name))
                    continue
                entry = re.compile(r"(r'" + re.escape(name) + r"': )(\w+)(,)")
                if not entry.search(body):
                    sys.exit(f"patch_dates: query {method}({name}) not found")
                body = entry.sub(r"\1jivoDateToQuery(\2)\3", body, count=1)
                remaining.discard((method, name))
                patched += 1
            source = source[: head.end()] + body + source[end:]
            changed = True
        if changed:
            path.write_text(add_import(source), encoding="utf-8", newline="\n")
    if remaining:
        sys.exit(f"patch_dates: methods not found: {sorted(remaining)}")
    return patched


def main() -> None:
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    spec = json.loads(pathlib.Path(sys.argv[1]).read_text(encoding="utf-8"))
    lib = pathlib.Path(sys.argv[2])
    (lib / "src" / "date_only.dart").write_text(HELPER, encoding="utf-8", newline="\n")
    fields = patch_models(lib, date_properties(spec))
    queries = patch_queries(lib, date_query_params(spec))
    print(f"  format: date -> YYYY-MM-DD: {fields} fields, {queries} query parameters")


if __name__ == "__main__":
    main()
